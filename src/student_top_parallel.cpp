// ============================================================================
// 256-way spatially-parallel batch inference top function, for csynth
// resource-utilization estimation ONLY. This is intentionally NOT wrapped
// in a runtime for-loop with an HLS UNROLL pragma over the pixel dimension.
// Writing 256 literal, separate calls removes all ambiguity for the HLS
// scheduler about whether these are independent hardware instances or a
// single loop body it needs to unroll-and-schedule as one unit -- the
// latter approach (unrolling a loop whose body contains 32-wide recurrent
// MAC trees) is exactly what produced the 50 GB OOM crash on a SINGLE
// pixel before the II=4 timing fix was applied to gru_cell_step. Each
// call below is independently resolved against the already-synthesizable
// student_infer_pixel function, which is a far cheaper scheduling problem
// for the tool to solve 256 times over than one 256-iteration unrolled
// loop.
//
// This function is NOT intended to be functionally simulated (csim) or
// deployed -- it exists solely so csynth_design can report DSP48E1, LUT,
// FF, and BRAM_18K totals for 256 parallel copies of the real single-pixel
// datapath on the actual target part (xc7k410t-ffg676-1, 4.5 ns clock).
// ============================================================================
